export const GITHUB_REPO_BLOB_BASE = "https://github.com/PaulKinlan/wasm-vs-js/blob/main";

export function toServedUrl(repoPath: string): string {
  if (!repoPath) return "";
  if (repoPath.startsWith("/")) return repoPath;
  if (repoPath.startsWith("public/")) return "/" + repoPath.slice("public/".length);
  return "/" + repoPath;
}

export function toGitHubBlobUrl(repoPath: string): string {
  if (!repoPath) return "";
  const clean = repoPath.replace(/^\//, "");
  return `${GITHUB_REPO_BLOB_BASE}/${clean}`;
}

