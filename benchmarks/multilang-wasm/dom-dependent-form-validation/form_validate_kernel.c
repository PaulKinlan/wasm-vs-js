// form_validate_kernel.c — multilang compute core for
// dom.dependent-form-validation.v1.
//
// ABI (mirrors benchmarks/multilang-wasm/dom-grid-movement/grid_kernel.c): the
// kernel GENERATES the frozen 240-action trace internally from the pinned
// seed (0x2468ace0), runs the JS reference model (runFormValidationJS: 10
// fields, per-rule validation for email/password/confirm/age/terms —
// totalErrors counts per-rule-per-action failures; activeErrorCount = rules
// currently failing at the end), writes counters to a FIXED memory offset,
// returns totalErrors.
//
// Results (fixed offset 16384):
//   [0] totalErrors [1] activeErrorCount [2] totalValidations
// Exports: i32 form_validate_trace() -> totalErrors

#define FIELDS 10
#define FIELD_CAP 32
#define ACTIONS 240
#define RES_OFFSET 16384

// field indices: 0 email, 1 password, 2 confirmPassword, 3 age, 4 country,
//                5 zipCode, 6 phone, 7 agreeTerms, 8 cardNumber, 9 cvv

static unsigned int seed = 0;
static double rand_next(void) {
  seed ^= seed << 13;
  // the engine's JS rand() applies >> 17 to the int32 interpretation
  // (arithmetic, sign-extending) — replicate exactly.
  seed ^= (unsigned int)((int)seed >> 17);
  seed ^= seed << 5;
  return (double)seed / 4294967296.0;
}

// Returns 1 if v[] is a valid email per /^[^\s@]+@[^\s@]+\.[^\s@]+$/.
static int email_valid(const unsigned char *v) {
  int len = 0;
  while (v[len]) len++;
  if (len == 0) return 0;
  int at = -1;
  for (int i = 0; i < len; i++) {
    if (v[i] == ' ' || v[i] == '\t' || v[i] == '\n' || v[i] == '\r') return 0;
    if (v[i] == '@') { if (at >= 0) return 0; at = i; }
  }
  if (at <= 0 || at >= len - 1) return 0;
  int dot = -1;
  for (int i = at + 1; i < len; i++) {
    if (v[i] == '@') return 0;
    if (v[i] == '.') dot = i;
  }
  if (dot < 0) return 0;
  if (dot == at + 1 || dot == len - 1) return 0;
  return 1;
}

// parseInt semantics: leading digits only, return NaN sentinel -1 if none.
// (all age values generated by the JS model are non-negative decimal digits.)
static int parse_age(const unsigned char *v) {
  int i = 0;
  while (v[i] == ' ' || v[i] == '\t') i++;
  int neg = 0;
  if (v[i] == '-') { neg = 1; i++; }
  int n = 0;
  int any = 0;
  while (v[i] >= '0' && v[i] <= '9') { n = n * 10 + (v[i] - '0'); any = 1; i++; }
  if (!any) return -1;
  return neg ? -n : n;
}

// hand-written strlen/strcmp to avoid clang emitting libc calls at -O3.
static __attribute__((noinline)) unsigned int str_len(const unsigned char *v) {
  unsigned int i = 0;
  while (v[i] != 0) i++;
  return i;
}

static __attribute__((noinline)) int str_equal(const unsigned char *a, const unsigned char *b) {
  unsigned int i = 0;
  for (;;) {
    if (a[i] != b[i]) return 0;
    if (a[i] == 0) return 1;
    i++;
  }
}

// Evaluate the 5 validation rules against the current fields[] state; sets
// *mask to a bitmask of failing rules and returns the number of failing rules.
static unsigned int validate(const unsigned char *fields, unsigned int *mask) {
  unsigned int m = 0;
  unsigned int errs = 0;
  const unsigned char *email = &fields[0 * FIELD_CAP];
  const unsigned char *password = &fields[1 * FIELD_CAP];
  const unsigned char *confirm = &fields[2 * FIELD_CAP];
  const unsigned char *age = &fields[3 * FIELD_CAP];
  const unsigned char *terms = &fields[7 * FIELD_CAP];
  // Rule 1: email set and invalid
  if (email[0] != 0 && !email_valid(email)) { m |= 1; errs++; }
  // Rule 2: password set and shorter than 8
  if (password[0] != 0 && str_len(password) < 8) { m |= 2; errs++; }
  // Rule 3: confirmPassword set and != password
  if (confirm[0] != 0 && !str_equal(confirm, password)) { m |= 4; errs++; }
  // Rule 4: age set and (parseInt < 18 or NaN)
  if (age[0] != 0) {
    const int a = parse_age(age);
    if (a < 0 || a < 18) { m |= 8; errs++; }
  }
  // Rule 5: terms set and != "true"
  if (terms[0] != 0 &&
      !(terms[0] == 't' && terms[1] == 'r' && terms[2] == 'u' && terms[3] == 'e' && terms[4] == 0)) {
    m |= 16; errs++;
  }
  *mask = m;
  return errs;
}

__attribute__((export_name("form_validate_trace")))
int form_validate_trace(void) {
  unsigned char fields[FIELDS * FIELD_CAP];
  unsigned char val[FIELD_CAP];
  unsigned int *results = (unsigned int *)RES_OFFSET;
  for (unsigned int i = 0; i < FIELDS * FIELD_CAP; i++) fields[i] = 0;

  seed = 0x2468ace0;
  unsigned int total_errors = 0;
  unsigned int total_validations = 0;

  for (int a = 0; a < ACTIONS; a++) {
    const int field = (int)(rand_next() * 10.0);
    const int val_len_alpha = 3 + (int)(rand_next() * 15.0);
    // Build the alpha-only base value (rand() consumed regardless of field).
    int vlen = 0;
    for (int j = 0; j < val_len_alpha; j++) {
      const int c = (int)(rand_next() * 26.0);
      if (vlen < FIELD_CAP - 1) val[vlen++] = (unsigned char)('a' + c);
    }
    if (field == 0) { // email → append "@example.com"
      const char suffix[] = "@example.com";
      for (int j = 0; j < 12; j++) {
        if (vlen < FIELD_CAP - 1) val[vlen++] = (unsigned char)suffix[j];
      }
    } else if (field == 3) { // age → String(15 + floor(rand()*50))
      const int age = 15 + (int)(rand_next() * 50.0);
      // decimal string (0..64) — at most 2 digits
      vlen = 0;
      char buf[8];
      int nb = 0;
      int x = age;
      do { buf[nb++] = (char)('0' + (x % 10)); x /= 10; } while (x);
      for (int j = nb - 1; j >= 0; j--) val[vlen++] = (unsigned char)buf[j];
    } else if (field == 7) { // agreeTerms → "true" if rand()>0.5 else "false"
      const int truthy = rand_next() > 0.5 ? 1 : 0;
      vlen = 0;
      if (truthy) {
        val[vlen++] = 't'; val[vlen++] = 'r'; val[vlen++] = 'u'; val[vlen++] = 'e';
      } else {
        val[vlen++] = 'f'; val[vlen++] = 'a'; val[vlen++] = 'l'; val[vlen++] = 's';
        val[vlen++] = 'e';
      }
    }
    // action type — consume the rand regardless; not otherwise used here.
    (void)rand_next();
    val[vlen] = 0;

    // Copy value into fields[field] (truncated to FIELD_CAP-1).
    unsigned char *dst = &fields[field * FIELD_CAP];
    int cp = 0;
    while (cp < vlen && cp < FIELD_CAP - 1) { dst[cp] = val[cp]; cp++; }
    dst[cp] = 0;
    total_validations++;

    unsigned int mask = 0;
    total_errors += validate(fields, &mask);
  }

  unsigned int mask = 0;
  const unsigned int active = validate(fields, &mask);
  results[0] = total_errors;
  results[1] = active;
  results[2] = total_validations;
  return (int)total_errors;
}
